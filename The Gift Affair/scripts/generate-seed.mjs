// Generates supabase/seed.sql from src/lib/demo/seed.json, so demo mode and the
// seeded database always contain the same sample content.
// Usage: node scripts/generate-seed.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const seed = JSON.parse(fs.readFileSync(path.join(root, "src/lib/demo/seed.json"), "utf8"));

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const b = (v) => (v ? "true" : "false");
const ago = (d) => `now() - interval '${Number(d)} days'`;
const lines = [
  "-- Sample content generated by scripts/generate-seed.mjs — do not edit by hand.",
  "-- Replace with real content before launch.",
  "begin;",
  "",
];

for (const c of seed.categories) {
  lines.push(
    `insert into public.categories (id, name, slug, description, image_path, sort_order, is_active) values (${q(c.id)}, ${q(c.name)}, ${q(c.slug)}, ${q(c.description)}, ${q(c.imagePath)}, ${c.sortOrder}, ${b(c.isActive)}) on conflict (id) do nothing;`,
  );
}
lines.push("");
for (const t of seed.tags) {
  lines.push(
    `insert into public.tags (id, name, slug, tag_type, description, sort_order, is_active) values (${q(t.id)}, ${q(t.name)}, ${q(t.slug)}, ${q(t.tagType)}, ${q(t.description)}, ${t.sortOrder}, ${b(t.isActive)}) on conflict (id) do nothing;`,
  );
}
lines.push("");

const catId = Object.fromEntries(seed.categories.map((c) => [c.slug, c.id]));
const tagId = (type, slug) => {
  const t = seed.tags.find((x) => x.tagType === type && x.slug === slug);
  if (!t) throw new Error(`Unknown ${type} tag: ${slug}`);
  return t.id;
};

for (const g of seed.gifts) {
  lines.push(
    `insert into public.gift_ideas (id, title, slug, summary, description, why_it_is_thoughtful, keywords, main_image_path, image_alt, external_url, source_name, is_featured, status, published_at, created_at) values (${q(g.id)}, ${q(g.title)}, ${q(g.slug)}, ${q(g.summary)}, ${q(g.description)}, ${q(g.whyThoughtful)}, ${q(g.keywords)}, ${q(g.mainImagePath)}, ${q(g.imageAlt)}, ${q(g.externalUrl)}, ${q(g.sourceName)}, ${b(g.isFeatured)}, 'published', ${ago(g.daysAgo)}, ${ago(g.daysAgo)}) on conflict (id) do nothing;`,
  );
  for (const s of g.categorySlugs) {
    if (!catId[s]) throw new Error(`Unknown category: ${s}`);
    lines.push(`insert into public.gift_category_links (gift_id, category_id) values (${q(g.id)}, ${q(catId[s])}) on conflict do nothing;`);
  }
  const tagIds = [
    ...g.occasionSlugs.map((s) => tagId("occasion", s)),
    ...g.recipientSlugs.map((s) => tagId("recipient", s)),
    ...(g.budgetSlug ? [tagId("budget", g.budgetSlug)] : []),
  ];
  for (const id of tagIds) {
    lines.push(`insert into public.gift_tag_links (gift_id, tag_id) values (${q(g.id)}, ${q(id)}) on conflict do nothing;`);
  }
  lines.push("");
}

const giftId = Object.fromEntries(seed.gifts.map((g) => [g.slug, g.id]));
for (const gd of seed.guides) {
  lines.push(
    `insert into public.gift_guides (id, title, slug, introduction, content, cover_image_path, cover_image_alt, status, published_at, created_at) values (${q(gd.id)}, ${q(gd.title)}, ${q(gd.slug)}, ${q(gd.introduction)}, ${q(gd.content)}, ${q(gd.coverImagePath)}, ${q(gd.coverImageAlt)}, 'published', ${ago(gd.daysAgo)}, ${ago(gd.daysAgo)}) on conflict (id) do nothing;`,
  );
  gd.giftSlugs.forEach((s, i) => {
    if (!giftId[s]) throw new Error(`Unknown gift in guide: ${s}`);
    lines.push(
      `insert into public.gift_guide_items (guide_id, gift_idea_id, sort_order) values (${q(gd.id)}, ${q(giftId[s])}, ${i}) on conflict do nothing;`,
    );
  });
  lines.push("");
}

lines.push("commit;", "");
fs.writeFileSync(path.join(root, "supabase/seed.sql"), lines.join("\n"));
console.log(`Wrote supabase/seed.sql (${seed.gifts.length} gifts, ${seed.guides.length} guides)`);
